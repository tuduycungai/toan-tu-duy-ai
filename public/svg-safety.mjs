/** Rebuild an SVG with an explicit tag/attribute allowlist. Never insert model HTML. */
export function sanitizeSVG(source){
 if(typeof source!=='string'||source.length>2500000||/<!DOCTYPE|<!ENTITY/i.test(source))throw Error('Ảnh SVG vượt giới hạn hoặc không an toàn.');
 const doc=new DOMParser().parseFromString(source,'image/svg+xml');
 if(doc.querySelector('parsererror')||doc.documentElement.localName!=='svg')throw Error('SVG không hợp lệ.');
 const tags=new Set(['svg','g','defs','path','line','polyline','polygon','rect','circle','ellipse','text','tspan','use','symbol','clipPath','mask','title','desc','style']);
 const attrs=new Set(['xmlns','xmlns:xlink','viewBox','width','height','x','y','x1','y1','x2','y2','cx','cy','r','rx','ry','d','points','transform','fill','stroke','stroke-width','stroke-linecap','stroke-linejoin','stroke-dasharray','stroke-dashoffset','fill-rule','clip-rule','opacity','fill-opacity','stroke-opacity','font-family','font-size','font-style','font-weight','text-anchor','dominant-baseline','dx','dy','id','clip-path','mask','href','xlink:href','color','preserveAspectRatio','style','class']);
 const all=[doc.documentElement,...doc.documentElement.querySelectorAll('*')];if(all.length>20000)throw Error('SVG quá phức tạp.');
 for(const node of all){
  if(!tags.has(node.localName)){node.remove();continue;}
  if(node.localName==='style'){
   // Only locally embedded font faces generated by the frame are allowed.
   const text=node.textContent||'';
   const rest=text.replace(/@font-face\{font-family:[a-zA-Z0-9]+;src:url\(data:font\/woff2;base64,[A-Za-z0-9+/=]+\) format\("woff2"\)\}/g,'');
   if(rest.trim())node.remove();continue;
  }
  for(const attr of [...node.attributes]){
   const name=attr.name,value=attr.value;
   if(!attrs.has(name)||/^on/i.test(name)||/[<>]|javascript:|https?:|data:|file:|@import|expression\s*\(/i.test(value)&&name!=='xmlns'&&name!=='xmlns:xlink'){node.removeAttribute(name);continue;}
   if((name==='href'||name==='xlink:href')&&!/^#[\w:.-]+$/.test(value))node.removeAttribute(name);
   if(/url\(/i.test(value)&&!/^url\(#[\w:.-]+\)$/.test(value))node.removeAttribute(name);
   if(name==='style'&&!/^(?:\s*(?:color|fill|stroke|stroke-width|font-size|font-family|opacity)\s*:\s*[#a-zA-Z0-9.,%()\s-]+;?\s*)*$/.test(value))node.removeAttribute(name);
  }
 }
 doc.documentElement.setAttribute('xmlns','http://www.w3.org/2000/svg');
 return new XMLSerializer().serializeToString(doc.documentElement);
}
